                        <p>
                            Asbestos is no longer being used in construction in Australia because of the overwhelming negative health effects it has on the human body. During the 20th century, asbestos was a staple in construction and was often used as a form on insulation due to its fire-resistant properties. If your home was built or renovated prior to the 1980’s there’s a good chance, there's asbestos somewhere in your home. Asbestos is only dangerous when disturbed, it's the tiny little fibres that harm us, so unless the asbestos is cracked or breaking down, it's unlikely to have negative impacts on your health. It doesn't hurt however to regularly check the asbestos in your home to ensure it’s still in good Knick.
                        </p>

                        <p>
                            <strong>Where is the Asbestos in Your Home Hiding?  </strong><br>

                            <strong>On and In Your Walls</strong> – Asbestos was used both internally and externally in the walls of older Aussie homes, particularly in the form of ‘Fibro’, which is upon first glance is quite similar to modern day fibre cement. The two types have subtle differences, including dimples in the material, and different colours. It can be difficult to be certain on whether or not the material is in fact asbestos, so it is of course always recommended to contact a professional.<br>
                            Asbestos materials were also used in loose insulation inside ceilings because of its fire-resistant qualities. This kind of asbestos is ‘friable’ meaning it easily crumples. This makes it quite dangerous and should only be handled by a professional.
                        </p>

                        <p>
                            <strong>In and on the Floor</strong> – Asbestos was used to strengthen lino which is used in flooring. Asbestos was also used in carpet underlay. If planning to renovate your home, remember that asbestos is very concentrated in these areas.
                        </p>

                        <p>
                            <strong>On Your Roof</strong> – Corrugated Asbestos Roofing was used in many builds. It’s a blend of cement and asbestos fibres. Being exposed to the elements on the outside of your home, the asbestos fibres on your roof may become disturbed. It’s important that you never walk on, drill into, or wash corrugated asbestos roofs, because this again will unsettle the particles.
                        </p>

